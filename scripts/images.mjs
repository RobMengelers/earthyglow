#!/usr/bin/env node
/**
 * Image pipeline for public/images.
 *
 * 1. Reads every .webp in public/images.
 * 2. Generates responsive width variants (`<name>-400.webp`, `<name>-800.webp`)
 *    whenever the original is meaningfully wider than the target.
 * 3. Regenerates src/data/imageMeta.ts with intrinsic dimensions + variants
 *    (consumed by src/lib/images.ts for width/height/srcset attributes).
 *
 * Run after adding or replacing product photography:
 *
 *   node scripts/images.mjs
 *
 * Requires the `sharp` devDependency. Variant files are committed.
 */
import { readdirSync, writeFileSync } from 'node:fs'
import { join, dirname, basename, extname } from 'node:path'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const imagesDir = join(root, 'public', 'images')
const outFile = join(root, 'src', 'data', 'imageMeta.ts')

const TARGET_WIDTHS = [400, 800]
/** Only create a variant when it is at least ~100px smaller than the original. */
const MIN_MARGIN = 100

const files = readdirSync(imagesDir).filter((f) => extname(f) === '.webp')
const entries = []

for (const file of files.sort()) {
  const stem = basename(file, '.webp')
  const original = join(imagesDir, file)
  const meta = await sharp(original).metadata()
  if (!meta.width || !meta.height) {
    throw new Error(`Could not read dimensions for ${file}`)
  }

  const variants = []
  for (const width of TARGET_WIDTHS) {
    if (meta.width < width + MIN_MARGIN) continue
    const variantFile = `${stem}-${width}.webp`
    await sharp(original)
      .resize({ width, withoutEnlargement: true })
      .webp({ quality: 82, effort: 4 })
      .toFile(join(imagesDir, variantFile))
    variants.push(width)
  }

  entries.push({
    path: `/images/${file}`,
    width: meta.width,
    height: meta.height,
    variants,
  })
}

const body = entries
  .map(
    (e) =>
      `  '${e.path}': { width: ${e.width}, height: ${e.height}, variants: [${e.variants.join(', ')}] },`,
  )
  .join('\n')

writeFileSync(
  outFile,
  `// Generated by scripts/images.mjs — do not edit by hand.
// Run \`node scripts/images.mjs\` after adding or replacing images in public/images.
export type ImageMeta = { width: number; height: number; variants: number[] }

export const imageMeta: Record<string, ImageMeta> = {
${body}
}
`,
)

console.log(`Processed ${entries.length} images, wrote ${outFile}`)
